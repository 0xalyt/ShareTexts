import React from 'react';
import { motion } from 'motion/react';
import { cn } from '../lib/utils';

/**
 * The ShareTexts mark — the OFFICIAL artwork, shipped as exact extracted
 * pixels. The four supplied logo tiles live in public/brand/logo-tile-*.jpg;
 * scripts/gen-logo-glyphs.mjs keys their flat field out to transparency
 * (glyph body pixels byte-exact, only the AA edge gets recomputed coverage)
 * into public/brand/logo-glyph-orange.png at a square canvas whose ink
 * height is 0.72 of the box — the geometry BrandLockup was measured
 * against, so every `size` prop keeps meaning exactly what it meant before.
 * The shape is never redrawn, traced, or recolored here: this component
 * only displays that file.
 *
 * Colorways:
 *   default — the ember glyph on BOTH themes. The mark never swaps to a
 *             cream/white colorway at night (design-owner decision, 2026-10;
 *             the cream tile asset stays archived but ships unused).
 *   mono    — the glyph silhouette as an alpha MASK painted with
 *             currentColor, for the few deliberate monochrome compositions
 *             (the missing-room tile, the transfer-complete pill) that tint
 *             the mark themselves.
 *
 * Motion states (optional):
 *   loading     — the mark breathes quietly (working)
 *   connecting  — a soft pulse while waiting for the peer
 *   transfer    — a quicker pulse (data in motion)
 *   complete    — settles static (the arrival is announced by its context)
 * Animations are skipped when prefers-reduced-motion is set — the mark
 * just sits there, so state stays legible.
 *
 * Must match public/favicon.svg (same glyph, generated by
 * scripts/gen-favicons-from-glyph.mjs).
 */

export type BrandMotion = 'loading' | 'connecting' | 'transfer' | 'complete';

// Read once at load; the reduced-motion preference rarely changes mid-session
// and MotionConfig already handles the JS-driven animations.
const reducedMotion = typeof window !== 'undefined'
  ? window.matchMedia('(prefers-reduced-motion: reduce)').matches
  : false;

// Exact glyph pixels (transparent field, 0.72 ink/box) from gen-logo-glyphs.
const GLYPH_ORANGE = '/brand/logo-glyph-orange.png';

export function ShareTextsLogo({
  className,
  size = 28,
  motion: motionState,
  mono = false,
}: {
  className?: string;
  size?: number;
  motion?: BrandMotion;
  /** Render as a currentColor silhouette (on-ink chips, tinted surfaces). */
  mono?: boolean;
}) {
  const inner = mono ? (
    // One mask source serves every tint: the silhouette is the artwork's
    // own alpha, the paint is the context's own color.
    <span
      className="block w-full h-full"
      style={{
        backgroundColor: 'currentColor',
        WebkitMaskImage: `url(${GLYPH_ORANGE})`,
        maskImage: `url(${GLYPH_ORANGE})`,
        WebkitMaskSize: 'contain',
        maskSize: 'contain',
        WebkitMaskRepeat: 'no-repeat',
        maskRepeat: 'no-repeat',
        WebkitMaskPosition: 'center',
        maskPosition: 'center',
      }}
    />
  ) : (
    <img
      src={GLYPH_ORANGE}
      alt=""
      draggable={false}
      decoding="async"
      className="w-full h-full"
    />
  );

  const rootStyle: React.CSSProperties = {
    width: size,
    height: size,
    // The lockup's outer span owns the box (the caller's w-full can style
    // it, maxWidth clamps it back) — same rendered result as the old svg's
    // presentation-attribute-vs-class precedence, without losing the
    // explicit pixel size for every other caller.
    maxWidth: '100%',
    maxHeight: '100%',
  };

  const animated =
    motionState && !reducedMotion && motionState !== 'complete'
      ? motionState
      : null;

  const root = animated ? (
    <motion.span
      aria-hidden
      className={cn('inline-block shrink-0', className)}
      style={rootStyle}
      animate={
        animated === 'loading'
          ? { scale: [1, 1.05, 1], opacity: [0.85, 1, 0.85] }
          : { opacity: animated === 'transfer' ? [1, 0.55, 1] : [1, 0.45, 1] }
      }
      transition={
        animated === 'loading'
          ? { duration: 1.8, repeat: Infinity, ease: 'easeInOut' }
          : { duration: animated === 'transfer' ? 1.1 : 1.7, repeat: Infinity, ease: 'easeInOut' }
      }
    >
      <span className="block w-full h-full">{inner}</span>
    </motion.span>
  ) : (
    <span aria-hidden className={cn('inline-block shrink-0', className)} style={rootStyle}>
      {inner}
    </span>
  );

  return root;
}

const enKeys = Object.keys(KEYS.en);

for (const [loc, map] of Object.entries(KEYS)) {
  const p = `src/lib/messages/${loc}.ts`;
  let src = readFileSync(p, 'utf8');
  if (src.includes("'saved.title'") || src.includes('"saved.title"')) {
    console.log(loc, '→ already has keys, skipped');
    continue;
  }
  const missing = enKeys.filter((k) => !(k in map));
  if (missing.length) throw new Error(`${loc}: missing keys: ${missing.join(', ')}`);
  const eol = src.includes('\r\n') ? '\r\n' : '\n';
  const idx = src.lastIndexOf('};');
  if (idx < 0) throw new Error(`${loc}: closing "}; not found`);
  const block = Object.entries(map)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join(eol);
  const insert = `  // ── saved items ────────────────────────────────────${eol}${block}${eol}`;
  src = src.slice(0, idx) + insert + src.slice(idx);
  writeFileSync(p, src);
  console.log(loc, `→ inserted ${enKeys.length} keys`, eol === '\r\n' ? '(crlf)' : '(lf)');
}
console.log('done');

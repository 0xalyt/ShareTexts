// gen-locale-status.mjs — keeps the locale status table out of the entry chunk.
//
// The rule (DESIGN.md §17, P6) is that a locale's status lives in the locale
// file, so the owner promotes a language by editing one line in the file they
// are already reading. That rule cost 160 KB of dictionaries in the first load,
// because `messages/meta.ts` had to import ten dictionaries to read one string
// from each — and a module that is statically imported *and* dynamically
// imported ends up in both places.
//
// So the string is read at build time instead. `meta.ts` imports the generated
// constant; the dictionaries stay lazy chunks.
//
//   node scripts/gen-locale-status.mjs          # write
//   node scripts/gen-locale-status.mjs --check  # fail if stale (used by CI)
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'src/lib/messages');
const OUT = join(DIR, 'status.generated.ts');
const CHECK = process.argv.includes('--check');

const CODES = ['en', 'es', 'fr', 'de', 'pt-BR', 'pt-PT', 'hi', 'ja', 'zh-Hans', 'zh-Hant', 'ar'];
const FILE_OF = {
  en: 'en', es: 'es', fr: 'fr', de: 'de', 'pt-BR': 'pt-BR', 'pt-PT': 'pt-PT',
  hi: 'hi', ja: 'ja', 'zh-Hans': 'zh-Hans', 'zh-Hant': 'zh-Hant', ar: 'ar',
};

const found = {};
const missing = [];
for (const code of CODES) {
  const file = join(DIR, `${FILE_OF[code]}.ts`);
  if (!existsSync(file)) { missing.push(`${code}: file absent`); continue; }
  const src = readFileSync(file, 'utf8');
  const m = src.match(/export const STATUS = '(draft|reviewed)' as const;/);
  if (!m) {
    // English carries no STATUS: it is the fallback dictionary and the one
    // locale that is reviewed by definition (registry.ts says the same).
    if (code === 'en') { found[code] = 'reviewed'; continue; }
    missing.push(`${code}: no STATUS export`);
    continue;
  }
  found[code] = m[1];
}

if (missing.length) {
  console.error(`[gen-locale-status] ${missing.length} locale(s) without a readable STATUS:`);
  for (const line of missing) console.error(`  ${line}`);
  process.exit(1);
}

const body = Object.entries(found)
  .map(([code, status]) => `  ${JSON.stringify(code)}: ${JSON.stringify(status)},`)
  .join('\n');

const next = `// GENERATED by scripts/gen-locale-status.mjs — do not edit by hand.
//
// The source of truth is the \`export const STATUS\` line in each dictionary.
// This file exists so that reading those statuses does not pull ten
// dictionaries into the entry chunk (P7 STEP 1b). Regenerate with
// \`node scripts/gen-locale-status.mjs\`; \`verify-bundle\` fails if it is stale.
import type { Lang } from './registry';

export const LOCALE_STATUS: Record<Lang, 'draft' | 'reviewed'> = {
${body}
};
`;

const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
if (CHECK) {
  if (current !== next) {
    console.error('[gen-locale-status] status.generated.ts is stale — run node scripts/gen-locale-status.mjs');
    process.exit(1);
  }
  console.log('[gen-locale-status] up to date');
} else if (current !== next) {
  writeFileSync(OUT, next);
  console.log(`[gen-locale-status] wrote ${Object.keys(found).length} statuses`);
} else {
  console.log('[gen-locale-status] up to date');
}

// The dictionary directory is also checked for stray files nobody registered —
// a locale added without a STATUS row is a silent draft, which the sheet then
// cannot label.
const strays = readdirSync(DIR)
  .filter((f) => f.endsWith('.ts') && !f.startsWith('_'))
  .filter((f) => !Object.values(FILE_OF).some((x) => `${x}.ts` === f))
  .filter((f) => !['registry.ts', 'types.ts', 'meta.ts', 'status.generated.ts'].includes(f));
if (strays.length) console.log(`[gen-locale-status] note: unregistered file(s): ${strays.join(', ')}`);

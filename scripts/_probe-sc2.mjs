import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await b.newPage();
const logs = [];
p.on('console', m => logs.push(`${m.type()}: ${m.text()}`));
p.on('pageerror', e => logs.push(`pageerror: ${e.message}`));
p.on('requestfailed', r => logs.push(`reqfail: ${r.url()} ${r.failure()?.errorText}`));
await p.goto('http://localhost:3010/space/create', { waitUntil: 'domcontentloaded' });
await p.waitForSelector('[data-testid="space-code-input"]', { timeout: 10000 });
const code = 'bse-' + Math.random().toString(36).slice(2, 6);
await p.fill('[data-testid="space-code-input"]', code);
await p.waitForTimeout(1500);
const status1 = await p.textContent('[data-testid="space-code-status"]').catch(() => '(none)');
const ctaDisabled = await p.getAttribute('[data-testid="space-create-cta"]', 'disabled');
const ctaAttrs = await p.evaluate(() => {
  const el = document.querySelector('[data-testid="space-create-cta"]');
  return el ? { disabled: el.disabled, aria: el.getAttribute('aria-disabled'), cls: el.className.slice(0,60) } : null;
});
console.log('status:', JSON.stringify(status1), 'cta:', JSON.stringify(ctaAttrs));
await p.click('[data-testid="space-create-cta"]');
await p.waitForTimeout(4000);
console.log('url after click:', p.url());
const status2 = await p.textContent('[data-testid="space-code-status"]').catch(() => '(gone)');
console.log('status2:', JSON.stringify(status2));
console.log('LOGS:'); console.log(logs.slice(-15).join('\n'));
await b.close();

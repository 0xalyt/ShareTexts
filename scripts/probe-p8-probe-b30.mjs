import { chromium } from 'playwright';
import { pairDevices } from './lib/flow.mjs';
const BASE = 'http://localhost:3390';
const b = await chromium.launch();
const c1 = await b.newContext({ viewport: { width: 1440, height: 900 } });
const c2 = await b.newContext({ viewport: { width: 390, height: 844 } });
const A = await c1.newPage(); const B = await c2.newPage();
await pairDevices(A, B, BASE);
await A.waitForTimeout(700);
const gear = A.locator('[data-testid="open-settings"]').first();
console.log('gear present:', await gear.count());
await gear.focus();
await gear.press('Enter');
await A.waitForTimeout(500);
console.log('after open  :', await A.evaluate(() => document.activeElement?.getAttribute('data-testid') || document.activeElement?.tagName));
await A.keyboard.press('Escape');
await A.waitForTimeout(600);
console.log('after escape:', await A.evaluate(() => document.activeElement?.getAttribute('data-testid') || document.activeElement?.tagName));
await b.close();
